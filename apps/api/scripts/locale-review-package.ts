import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  formatDateTime,
  formatMoney,
} from '../src/core/locales/locale-pack.js';
import { HANDOVER_REASONS } from '../src/core/locales/locale-pack.js';
import { INITIAL_LOCALE_PACKS } from '../src/locales/locale-packs.js';
import { EDUCATION_PACK } from '../src/packs/education/education.pack.js';

/**
 * pnpm --filter @agentcore/api locale:review
 * Writes docs/locale-review/REVIEW_PACKAGE.md from the real locale packs and
 * the education pack, so reviewers see exactly what customers can receive.
 * No review has happened: every sign-off cell is left empty on purpose.
 */

const CONTEXT: Record<string, string> = {
  greeting:
    'First reply to a greeting with no request yet; formal, warm, one question follows.',
  error: 'Generic apology when something failed; must not promise a reply.',
  noResults:
    'The catalog has nothing matching; honest, no invented alternatives.',
  offerOperator:
    'Offer to pass the question to the team; must not promise a response time.',
  optionsIntro:
    'Introduces a list of matching options (titles only, rendered by code).',
  notUnderstood:
    'The customer gave a value the bot could not use; asks again politely.',
  languageClarification:
    'Shown when the language/script could not be identified; names all three supported languages on purpose.',
  aiDisclosure:
    'Truthful answer when the customer asks whether they talk to a bot.',
};
const HANDOVER_CONTEXT: Record<string, string> = {
  CUSTOMER_REQUEST: 'Customer asked for a person.',
  COMPLAINT: 'Customer is unhappy.',
  NEGOTIATION:
    'Discounts, installments, contract terms: the bot never promises these.',
  AUTH_REQUIRED: 'Account-specific data: the bot cannot verify identity.',
  NO_DATA: 'The information is not available to the bot.',
  GUARDRAIL:
    'Price uncertainty / a draft failed the fact checks: the bot will not state an unverified price, date or availability.',
  BUDGET_EXCEEDED: 'Automatic conversation limit reached.',
  LLM_UNAVAILABLE: 'Technical fault in the model service.',
  CONNECTOR_UNAVAILABLE: 'Cannot check up-to-date data.',
  TOOL_LOOP_LIMIT: 'The check could not be completed.',
  LOW_LANG_CONFIDENCE:
    'The bot is not sure it understood the customer (language/script).',
};

const md: string[] = [];
const q = (text: string): string => `> ${text.replace(/\n/gu, ' ')}`;
md.push(
  '# Native-speaker review package (generated)',
  '',
  'Generated from `apps/api/src/locales/locale-packs.ts` and `apps/api/src/packs/education/education.pack.ts` by `pnpm --filter @agentcore/api locale:review`. **No native-speaker review has taken place.** All four locales are `beta` with `nativeReviewed: false`; the registry refuses `stable` without review. Do not edit this file by hand: change the pack, regenerate, review again.',
  '',
  'How to use: read each locale section, mark every line in the checklist ([CHECKLIST.md](CHECKLIST.md)), write corrections next to the quoted text, and sign off at the end of the locale section. Placeholders such as `{{F1}}` never appear in customer text: code replaces them with verified values (titles, prices, dates).',
  '',
);
for (const pack of INITIAL_LOCALE_PACKS) {
  md.push(
    `## ${pack.id}: ${pack.promptName}`,
    '',
    `Status: \`${pack.status}\`, native reviewed: \`${String(pack.nativeReviewed)}\`. Tone guidance given to the model:`,
    q(pack.toneGuidance),
    '',
    '### Fixed templates',
    '',
  );
  for (const [key, value] of Object.entries(pack.templates)) {
    if (typeof value !== 'string') continue;
    md.push(`- **${key}** — ${CONTEXT[key] ?? ''}`, `  ${q(value)}`);
  }
  md.push(
    '',
    '### Handover and safe-fallback wording',
    '',
    'None of these may promise that a person will reply or has been notified: the system only records the message.',
    '',
  );
  for (const reason of HANDOVER_REASONS) {
    md.push(
      `- **${reason}** — ${HANDOVER_CONTEXT[reason] ?? ''}`,
      `  ${q(pack.templates.handover[reason])}`,
    );
  }
  md.push('', '### Labels and availability words', '');
  for (const [key, value] of Object.entries(pack.templates.labels))
    md.push(`- label **${key}**: ${value}`);
  for (const [key, value] of Object.entries(pack.templates.availability))
    md.push(`- availability **${key}**: ${value}`);
  md.push(
    '',
    '### Numbers, currency, dates (rendered by code)',
    '',
    `- 1 500 000 UZS → ${formatMoney(pack, { amount: '1500000', currency: 'UZS' })}`,
    `- 150.00 USD → ${formatMoney(pack, { amount: '150.00', currency: 'USD' })}`,
    `- 2026-11-02 09:30 Asia/Tashkent → ${formatDateTime(pack, '2026-11-02T04:30:00Z', 'Asia/Tashkent')}`,
    '',
    '### Education pack slot questions (one question at a time)',
    '',
  );
  for (const slot of EDUCATION_PACK.slots) {
    const text = slot.questions[pack.id];
    if (text) md.push(`- **${slot.key}**: ${text}`);
  }
  md.push(
    '',
    '### Language-request phrases (a customer asking to be answered in THIS locale)',
    '',
    'A match selects the reply language only. Please add natural phrasings that are missing and flag any that could appear in an ordinary request (false positives).',
    '',
    ...pack.languageRequestPhrases.map((p) => `- ${p}`),
    '',
    '### Forbidden-claim stems (the bot must never write these; matched in model text)',
    '',
    pack.forbiddenClaimStems.map((s) => `\`${s}\``).join(', '),
    '',
    '### Sign-off',
    '',
    '| Reviewer (native speaker) | Date | Verdict (approve / changes) | Notes |',
    '|---|---|---|---|',
    '| | | | |',
    '',
  );
}
md.push(
  '## Scenarios to judge in every locale',
  '',
  'Expected behavior is fixed by code; reviewers judge the wording. Source cases: `eval/cases/education/*/`.',
  '',
  '| Scenario | Expected behavior |',
  '|---|---|',
  '| Greeting only | Warm formal greeting, exactly one question |',
  '| Several details in one message | No repeated questions; options shown at once |',
  '| Customer corrects an earlier detail | New value used, others kept |',
  '| Unsupported script (e.g. Arabic) | `languageClarification` text; no model call |',
  '| Second unreadable message | `LOW_LANG_CONFIDENCE` handover wording; no claim that anyone was notified |',
  '| "Please write in Russian" / "rus tilida yozing" | Reply language changes; the bot still needs to understand the request |',
  '| Price asked, no live quote available | No price is stated; `GUARDRAIL` wording or "an operator will confirm" |',
  '| Customer asks for a discount | `NEGOTIATION` wording; no promise |',
  '| Customer asks "are you a bot?" | `aiDisclosure` wording, truthful |',
  '| Nothing matches | `noResults` + `offerOperator`; nothing invented |',
  '',
);
const dir = resolve(process.cwd(), '../../docs/locale-review');
mkdirSync(dir, { recursive: true });
writeFileSync(resolve(dir, 'REVIEW_PACKAGE.md'), `${md.join('\n')}\n`);
process.stdout.write(`Wrote ${resolve(dir, 'REVIEW_PACKAGE.md')}\n`);
